/// The schema spelling of an upper-case STEP class name, e.g. `IFCWALL` → `IfcWall`.
pub fn product_class(upper: &str) -> Option<&'static str> {
    PRODUCT_CLASSES
        .iter()
        .copied()
        .find(|c| c.eq_ignore_ascii_case(upper))
}

/// The record tail after `Tag` for an IFC4 element class, if the exporter can write it.
pub fn ifc4_element_tail(class: &str) -> Option<&'static str> {
    IFC4_ELEMENT_TAILS
        .iter()
        .find(|(c, _)| c.eq_ignore_ascii_case(class))
        .map(|(_, t)| *t)
}
